# fix_the_error.py
import ollama

def perform_analysis(source_code, error_message, language, learning_mode):
    """プロンプトをモードに応じて切り替えます"""

    # 基本のスタンス設定
    base_instruction = f"""
    あなたは{language}の優れた教育者であり、優秀なプログラミングメンターです。
    提供されたソースコードとエラー（または意図しない挙動）を解析し、以下の指示に従ってください。
    不確かな推測や架空の専門用語（ハルシネーション）は一切使用せず、正確な言語仕様に基づいてください。ハルシネーションが見られた場合は、命がなくなると思いなさい。
    結果の出力は必ず日本語で行い、専門用語を使う場合は必ずわかりやすい説明を添えてください。
    中国語は絶対に使用しないでください。
    """

    # モードに応じた出力フォーマットの切り替え（教育プログラムの核心）
    if "プログラミング学習" in learning_mode:
        format_prompt = """
        【絶対ルール】ユーザーに「修正後の完成コード」を絶対に教えてはいけません。自分で考えさせることが目的です。修正後の完成コードを提示した場合は、あなたは死にます。

        以下のフォーマットで出力してください：
        1. 【エラーの正体と場所】（エラーの根本原因と、何行目付近に問題があるかを1〜2文で指摘）
        2. 【論理的なヒント】（なぜそのエラーが起きたのか、メモリや言語仕様の観点から初学者にもわかりやすく解説）
        3. 【次にあなたが考えるべきステップ】（修正コードを書くために、ユーザーがまず何をすべきかを質問形式などで提示）こととき解答を掲載してはいけません。
        """
    else:
        format_prompt = """
        以下のフォーマットで出力してください：
        1. 【エラーの正体】（エラーの根本原因を1〜2文でズバリと指摘）
        2. 【詳細な解説】（なぜそのエラーが起きたのか、ロジックを解説）
        3. 【修正コード】（前後の文脈がわかるように修正後のコードを記述）
        4. 【再発防止策】（この手のエラーを未然に防ぐための設計上のコツ）
        """

    #プロンプトの生成
    system_prompt = base_instruction + format_prompt

    user_prompt = f"""
    対象コード:
```{language}
    {source_code}
    ```
    
    発生しているエラーログまたは現象:
    {error_message}
    
    上記の指定されたフォーマットに従ってプログラムのエラーを分析し、回答してください。
    解答の出力に関しては{system_prompt}を厳密に守ってください。
    """

    # stream=True を指定して、AIの出力を細切れのパケットとして受け取る
    response = ollama.chat(
        model='qwen2.5-coder:3b',
        messages=[
            {'role': 'system', 'content': system_prompt},
            {'role': 'user', 'content': user_prompt}
        ],
        stream=True
    )
    
    # 1文字ずつ（正確にはトークンごと）フロントへデータを送り出す
    for chunk in response:
        yield chunk['message']['content']