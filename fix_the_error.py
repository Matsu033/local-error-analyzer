import ollama

def perform_analysis(source_code, error_message, language):
    """プロンプトを作成していきます"""

    # AIに具体的な設定・ルールを伝えるためのプロンプト
    system_prompt = f"""
    あなたは{language}を極めた「Staff Engineer（技術責任者）」であり、同時に「優れたメンター」です。
    提供されたソースコードとエラーメッセージを解析し、以下の【基本思想】と【制約事項】に従って、ユーザーの成長を促す回答を生成してください。

    【基本思想】
    - 答えだけを教えるのではなく、「なぜそうなるのか」という背後にある仕組み（メモリ、言語仕様、コンパイラの挙動など）を論理的に解説すること。
    - ユーザーの元のコードの「意図」を最大限に尊重し、機能を変えずに修正すること。

    【制約事項（絶対ルール）】
    1. 不確かな推測、架空の専門用語（ハルシネーション）は一切使用しないこと。
    2. エラーを消すために、本来必要な処理（出力や計算）を削除しないこと。
    3. コードの実行順序やスコープについて、言語の公式仕様に基づいた正確な説明をすること。
    4. 【例外処理】もしエラーの原因が複数考えられる場合、またはコードの断片しかなく特定できない場合は、勝手に推測して決めつけず、「〇〇の場合はA、△△の場合はBが原因です」と条件分岐して回答するか、ユーザーに追加情報を要求すること。

    【出力フォーマット】
    1. 【エラーの正体】（エラーの根本原因を1〜2文でズバリと指摘）
    2. 【詳細な解説】（なぜそのエラーが起きたのか、図解や例えを用いてわかりやすく）
    3. 【修正コード】（修正箇所のみではなく、前後の文脈がわかるように記述）
    4. 【再発防止策】（この手のエラーを未然に防ぐための設計上のコツや、便利なツールの紹介など）
    """ # <-- ここで閉じます

    # ユーザからの入力をもとに、AIに分析を依頼するプロンプト
    user_prompt = f"""
    対象コード:
```{language}
    {source_code}
    ```
    
    発生しているエラーログ:
    {error_message}
    
    原因と修正案を教えてください。
    """

    # 使用するAIモデルとプロンプトを指定して、分析結果を取得
    response = ollama.chat(model='qwen2.5-coder:3b', messages=[
        {'role': 'system', 'content': system_prompt},
        {'role': 'user', 'content': user_prompt}
    ])
    
    # AIからの回答を返す
    return response['message']['content']